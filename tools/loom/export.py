#!/usr/bin/env python3
"""Assemble Loom programs + engine configuration into a plain-data Python module that
the MicroPython host driver (host/loomhost.py) can load with Loom.run(APP).

usage:
  python3 tools/loom/export.py ENGINE:ORIGIN:PROGRAM.loom[:key=value,...] ... [--gpio 0x2000] [--od 0x3]

example (UART TX on GPIO13 at 115200 baud, 30 MHz clock):
  python3 tools/loom/export.py \\
    0:0:programs/uart_tx.loom:clkdiv=65.104,out_base=13,out_count=1,sideset_base=13,out_shift_right=1 \\
    --gpio 0x2000 > uart_demo.py
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from loom.asm import assemble_file  # noqa: E402
from loom import regs as R  # noqa: E402


def parse_kv(s):
    out = {}
    for item in filter(None, s.split(",")):
        k, v = item.split("=")
        v = v.strip()
        if v.lower() in ("true", "false"):
            out[k] = v.lower() == "true"
        elif "." in v:
            out[k] = float(v)
        else:
            out[k] = int(v, 0)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("engines", nargs="+")
    ap.add_argument("--gpio", type=lambda x: int(x, 0))
    ap.add_argument("--od", type=lambda x: int(x, 0))
    a = ap.parse_args(argv)
    apps = []
    for spec in a.engines:
        parts = spec.split(":", 3)
        eng, origin, path = int(parts[0]), int(parts[1], 0), parts[2]
        kw = parse_kv(parts[3]) if len(parts) > 3 else {}
        prog = assemble_file(path)
        cfg = prog.config(origin, **kw)
        regs = cfg.regs()
        regs[R.CRCVAL] = cfg.crc_init_value()
        apps.append({"engine": eng, "origin": origin, "program": prog.name,
                     "code": prog.relocated(origin), "regs": regs,
                     "labels": {k: (v + origin) & 63 for k, v in prog.labels.items()}})
    app = {"engines": apps}
    if a.gpio is not None:
        app["gpio"] = [a.gpio]
    if a.od is not None:
        app["od"] = a.od
    print("# generated by tools/loom/export.py")
    print("APP = " + repr(app))


if __name__ == "__main__":
    main()
